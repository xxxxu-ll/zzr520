  /* ------------------------------------------------------------------
     生成：用 hash 取样，保证同一天同一星座稳定、跨天不按顺序
     ------------------------------------------------------------------ */
  function hash(value) {
    let n = 2166136261;
    for (const c of value) { n ^= c.charCodeAt(0); n = Math.imul(n, 16777619); }
    return n >>> 0;
  }

  function dayKey(now = new Date()) {
    const parts = new Intl.DateTimeFormat('en-US', { timeZone: 'Asia/Shanghai', year: 'numeric', month: '2-digit', day: '2-digit' }).formatToParts(now);
    const pickPart = type => parts.find(p => p.type === type).value;
    return `${pickPart('year')}-${pickPart('month')}-${pickPart('day')}`;
  }

  function validDate(value) {
    return /^\d{4}-\d{2}-\d{2}$/.test(value || '')
      && Number.isFinite(Date.parse(value + 'T00:00:00Z'))
      && new Date(value + 'T00:00:00Z').toISOString().slice(0, 10) === value;
  }

